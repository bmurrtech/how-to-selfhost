#!/usr/bin/env bash
# config_env.sh — interactive/idempotent .env bootstrap for local-ai recipes.
# shellcheck shell=bash
#
# Usage (after recipe_bootstrap or with ROOT_DIR set):
#   source "${LIB_DIR}/config_env.sh"
#   config_env_ensure
#   config_env_show_token
#
# After ensure, CONFIG_ENV_KEY_SOURCE is one of: environment | generated | dotenv
# CONFIG_ENV_HF_SOURCE is one of: environment | dotenv | absent

config_env_path() {
	echo "${ROOT_DIR:?ROOT_DIR required}/.env"
}

config_env_example_path() {
	echo "${ROOT_DIR}/.env.example"
}

config_env_generate_api_key() {
	if command -v openssl >/dev/null 2>&1; then
		openssl rand -hex 32
		return 0
	fi
	if [[ -r /dev/urandom ]]; then
		# shellcheck disable=SC2002
		od -An -N32 -tx1 /dev/urandom | tr -d ' \n'
		echo
		return 0
	fi
	echo "error: need openssl or /dev/urandom to generate VLLM_API_KEY" >&2
	return 1
}

# Predictable RunPod-style default: sk-${RUNPOD_POD_ID}
_config_env_is_weak_runpod_key() {
	local key="$1"
	[[ -n "${RUNPOD_POD_ID:-}" && -n "$key" && "$key" == "sk-${RUNPOD_POD_ID}" ]]
}

_config_env_get() {
	local key="$1" file
	file="$(config_env_path)"
	[[ -f "$file" ]] || return 1
	local line val
	while IFS= read -r line || [[ -n "$line" ]]; do
		line="${line%$'\r'}"
		[[ -z "$line" || "$line" =~ ^[[:space:]]*# ]] && continue
		[[ "$line" != "${key}="* ]] && continue
		val="${line#*=}"
		if [[ "$val" =~ ^\".*\"$ ]]; then
			val="${val:1:${#val}-2}"
		elif [[ "$val" =~ ^\'.*\'$ ]]; then
			val="${val:1:${#val}-2}"
		fi
		[[ -z "$val" ]] && return 1
		printf '%s' "$val"
		return 0
	done <"$file"
	return 1
}

_config_env_upsert() {
	local key="$1" value="$2" file tmp
	file="$(config_env_path)"
	tmp="$(mktemp)"
	if [[ -f "$file" ]]; then
		awk -v k="$key" -v v="$value" '
			BEGIN { done=0 }
			$0 ~ "^" k "=" {
				print k "=" v
				done=1
				next
			}
			{ print }
			END { if (!done) print k "=" v }
		' "$file" >"$tmp"
	else
		printf '%s=%s\n' "$key" "$value" >"$tmp"
	fi
	mv -f "$tmp" "$file"
	chmod 600 "$file"
}

_config_env_ensure_file() {
	local env_file example
	env_file="$(config_env_path)"
	example="$(config_env_example_path)"

	if [[ ! -f "$env_file" ]]; then
		if [[ -f "$example" ]]; then
			cp "$example" "$env_file"
		else
			cat >"$env_file" <<'EOF'
# Generated by just config — secrets only; mode 0600
VLLM_API_KEY=
HF_TOKEN=
EOF
		fi
		chmod 600 "$env_file"
		echo "created ${env_file} (mode 0600)"
	else
		chmod 600 "$env_file" 2>/dev/null || true
		echo "using existing ${env_file}"
	fi
}

_config_env_offer_generate_key() {
	local ans="Y"
	if [[ -t 0 ]]; then
		read -r -p "Generate a strong VLLM_API_KEY into .env? [Y/n] " ans || true
		ans="${ans:-Y}"
		if [[ "$ans" == "n" || "$ans" == "N" ]]; then
			return 1
		fi
	fi
	return 0
}

config_env_ensure() {
	local prompt_hf="${CONFIG_PROMPT_HF_TOKEN:-1}"
	local env_key="" file_key="" key=""

	_config_env_ensure_file

	CONFIG_ENV_KEY_SOURCE=""
	CONFIG_ENV_HF_SOURCE=""
	export CONFIG_ENV_KEY_SOURCE CONFIG_ENV_HF_SOURCE

	# --- VLLM_API_KEY precedence ---
	env_key="${VLLM_API_KEY:-}"
	file_key="$(_config_env_get VLLM_API_KEY || true)"

	if [[ -n "$env_key" ]] && ! _config_env_is_weak_runpod_key "$env_key"; then
		# Strong env / Secret — do not copy into .env
		CONFIG_ENV_KEY_SOURCE=environment
		echo "VLLM_API_KEY: provided by environment"
	elif [[ -n "$env_key" ]] && _config_env_is_weak_runpod_key "$env_key"; then
		echo "warn: VLLM_API_KEY matches predictable RunPod default (sk-\$RUNPOD_POD_ID)" >&2
		if _config_env_offer_generate_key; then
			key="$(config_env_generate_api_key)" || return 1
			_config_env_upsert VLLM_API_KEY "$key"
			export VLLM_API_KEY="$key"
			CONFIG_ENV_KEY_SOURCE=generated
			echo "VLLM_API_KEY: generated (overrides weak provider default)"
		elif [[ -n "$file_key" ]] && ! _config_env_is_weak_runpod_key "$file_key"; then
			export VLLM_API_KEY="$file_key"
			CONFIG_ENV_KEY_SOURCE=dotenv
			echo "VLLM_API_KEY: using .env (kept weak env key out of deploy path)"
		else
			CONFIG_ENV_KEY_SOURCE=environment
			echo "VLLM_API_KEY: keeping weak env key (operator declined generate)" >&2
		fi
	elif [[ -n "$file_key" ]]; then
		export VLLM_API_KEY="$file_key"
		CONFIG_ENV_KEY_SOURCE=dotenv
		echo "VLLM_API_KEY: preserved"
	else
		key="$(config_env_generate_api_key)" || return 1
		_config_env_upsert VLLM_API_KEY "$key"
		export VLLM_API_KEY="$key"
		CONFIG_ENV_KEY_SOURCE=generated
		echo "VLLM_API_KEY: generated"
	fi

	# --- HF_TOKEN: env/Secret wins; never copy from env into .env ---
	# Resolve aliases (HUGGING_FACE_HUB_TOKEN / RUNPOD_SECRET_HF_TOKEN) first.
	if declare -F local_ai_resolve_hf_token >/dev/null 2>&1; then
		local_ai_resolve_hf_token
	fi
	if [[ -n "${HF_TOKEN:-}" ]]; then
		CONFIG_ENV_HF_SOURCE="${CONFIG_ENV_HF_SOURCE:-environment}"
		if [[ "${CONFIG_ENV_HF_SOURCE}" == "dotenv" ]]; then
			echo "HF_TOKEN: preserved"
		else
			CONFIG_ENV_HF_SOURCE=environment
			echo "HF_TOKEN: provided by environment (not copied into .env)"
		fi
	elif file_key="$(_config_env_get HF_TOKEN || true)" && [[ -n "$file_key" ]]; then
		export HF_TOKEN="$file_key"
		export HUGGING_FACE_HUB_TOKEN="$file_key"
		CONFIG_ENV_HF_SOURCE=dotenv
		echo "HF_TOKEN: preserved"
	elif [[ "$prompt_hf" == "1" && -t 0 ]]; then
		local hf=""
		echo "HF_TOKEN: optional — prefer a RunPod Secret (or other host Secret) over pasting here"
		read -r -s -p "HF_TOKEN (Enter to skip): " hf || true
		echo
		if [[ -n "$hf" ]]; then
			_config_env_upsert HF_TOKEN "$hf"
			export HF_TOKEN="$hf"
			export HUGGING_FACE_HUB_TOKEN="$hf"
			CONFIG_ENV_HF_SOURCE=dotenv
			echo "HF_TOKEN: set"
		else
			CONFIG_ENV_HF_SOURCE=absent
			echo "HF_TOKEN: left blank"
		fi
	else
		CONFIG_ENV_HF_SOURCE=absent
		echo "HF_TOKEN: blank (set as Secret/env if gated download needed)"
	fi

	if declare -F local_ai_load_env >/dev/null 2>&1; then
		local_ai_load_env "${RECIPE_DIR:-}"
		# Re-assert generated/dotenv key if load_env left a weak shell export in place.
		if [[ "${CONFIG_ENV_KEY_SOURCE}" == "generated" || "${CONFIG_ENV_KEY_SOURCE}" == "dotenv" ]]; then
			file_key="$(_config_env_get VLLM_API_KEY || true)"
			[[ -n "$file_key" ]] && export VLLM_API_KEY="$file_key"
		fi
		# Re-assert HF after load_env (empty .env must not clobber Secret).
		if declare -F local_ai_resolve_hf_token >/dev/null 2>&1; then
			local_ai_resolve_hf_token
		fi
		if [[ -n "${HF_TOKEN:-}" && -z "${CONFIG_ENV_HF_SOURCE:-}" ]]; then
			CONFIG_ENV_HF_SOURCE=environment
		elif [[ -z "${HF_TOKEN:-}" ]]; then
			CONFIG_ENV_HF_SOURCE=absent
		fi
	fi
}

config_env_show_token() {
	local key
	key="${VLLM_API_KEY:-}"
	if [[ -z "$key" ]]; then
		key="$(_config_env_get VLLM_API_KEY || true)"
	fi
	if [[ -z "$key" ]]; then
		echo "VLLM_API_KEY not set — run: just config" >&2
		return 1
	fi
	printf '%s\n' "$key"
}

# If shell has predictable RunPod sk-$POD_ID but .env has a stronger key, prefer .env.
config_env_prefer_strong_api_key() {
	local file_key=""
	if [[ -z "${VLLM_API_KEY:-}" ]] || ! _config_env_is_weak_runpod_key "${VLLM_API_KEY}"; then
		return 0
	fi
	file_key="$(_config_env_get VLLM_API_KEY || true)"
	if [[ -n "$file_key" ]] && ! _config_env_is_weak_runpod_key "$file_key"; then
		export VLLM_API_KEY="$file_key"
	fi
}

# Non-secret operator summary (paths + presence only).
config_env_summary() {
	local ws="(none)"
	local key_src="${CONFIG_ENV_KEY_SOURCE:-unknown}"
	local hf_src="${CONFIG_ENV_HF_SOURCE:-unknown}"
	local mode="${1:-}"

	if [[ -d /workspace && -w /workspace ]]; then
		ws="/workspace (writable)"
	elif [[ -d /workspace ]]; then
		ws="/workspace (not writable)"
	elif [[ -d /runpod-volume ]]; then
		ws="/runpod-volume"
	fi

	echo "=== config summary ==="
	[[ -n "$mode" ]] && echo "Exec mode:     ${mode}"
	echo "Workspace:     ${ws}"
	if declare -F local_ai_resolve_hf_token >/dev/null 2>&1; then
		local_ai_resolve_hf_token
		hf_src="${CONFIG_ENV_HF_SOURCE:-absent}"
	fi
	if [[ -n "${HF_TOKEN:-}" ]]; then
		hf_src="${hf_src:-present}"
		[[ "$hf_src" == "absent" || "$hf_src" == "unknown" ]] && hf_src=present
	else
		hf_src=absent
	fi
	echo "VLLM_API_KEY:  ${key_src} (value not shown)"
	echo "HF_TOKEN:      ${hf_src} (value not shown)"
	echo "HF_CACHE:      ${HF_CACHE:-unset}"
	echo "HF_HOME:       ${HF_HOME:-${HF_CACHE:-unset}}"
	echo "VLLM_CACHE_ROOT: ${VLLM_CACHE_ROOT:-unset}"
}
