#!/usr/bin/env bash
# resolve_dense_serve.sh — write .runtime.env for dense NVFP4 serve (no PLE mmap).
# shellcheck shell=bash
#
# Requires resolve_serve.sh (via recipe_common): resolve_snapshot_in, _runtime_escape.

resolve_dense_serve_write() {
	local out="${1:?output path}"
	local model="${MODEL:-${VLLM_MODEL:-bottlecapai/ThinkingCap-Qwen3.8-27B-NVFP4}}"
	local image="${IMAGE:-ghcr.io/styles01/qwen38-mtp3:latest}"
	local name="${NAME:-thinkingcap-qwen38-27b-nvfp4}"
	local port="${PORT:-8000}"
	local ctx="${CTX:-262144}"
	local seqs="${SEQS:-4}"
	local gpu_mem="${GPU_MEM:-0.75}"
	local mtp="${MTP:-3}"
	local prefix_cache="${PREFIX_CACHE:-1}"
	local batched="${MAX_NUM_BATCHED_TOKENS:-8192}"
	local shm="${SHM_SIZE:-16g}"
	local hf_cache="${HF_CACHE:-${HOME}/.cache/huggingface}"
	local served="${SERVED_MODEL_NAME:-ThinkingCap-Qwen3.8-27B}"
	local kv_dtype="" pc_arg spec_json api_extra snap_in hash_src hash

	if [[ "${PASS_KV_DTYPE:-0}" == "1" ]]; then
		kv_dtype="${KV_DTYPE:-fp8}"
	fi

	MODEL="$model"
	IMAGE="$image"
	HF_CACHE="$hf_cache"
	export MODEL IMAGE HF_CACHE

	snap_in="$(resolve_snapshot_in)" || return 1

	pc_arg="--no-enable-prefix-caching"
	[[ "$prefix_cache" == "1" ]] && pc_arg="--enable-prefix-caching"

	spec_json=""
	if [[ "$mtp" != "0" ]]; then
		spec_json="{\"method\":\"mtp\",\"num_speculative_tokens\":${mtp}}"
	fi

	api_extra="${EXTRA:-}"

	hash_src="${image}|${name}|${port}|${ctx}|${seqs}|${gpu_mem}|${mtp}|${prefix_cache}|${kv_dtype}|${snap_in}|${batched}|${served}"
	hash="$(printf '%s' "$hash_src" | sha256sum | awk '{print $1}')"

	umask 077
	cat >"$out" <<EOF
# Generated by resolve_dense_serve.sh — do not commit
IMAGE=$(_runtime_escape "$image")
NAME=$(_runtime_escape "$name")
PORT=$(_runtime_escape "$port")
HF_CACHE=$(_runtime_escape "$hf_cache")
SHM_SIZE=$(_runtime_escape "$shm")
SNAP_IN=$(_runtime_escape "$snap_in")
CTX=$(_runtime_escape "$ctx")
SEQS=$(_runtime_escape "$seqs")
GPU_MEM=$(_runtime_escape "$gpu_mem")
KV_DTYPE=$(_runtime_escape "$kv_dtype")
MAX_NUM_BATCHED_TOKENS=$(_runtime_escape "$batched")
PREFIX_CACHE_ARG=$(_runtime_escape "$pc_arg")
SPEC_JSON=$(_runtime_escape "$spec_json")
EXTRA_ARGS=$(_runtime_escape "$api_extra")
CONFIG_HASH=$hash
SERVED_MODEL_NAME=$(_runtime_escape "$served")
COMPOSE_PROJECT_NAME=$(_runtime_escape "${COMPOSE_PROJECT_NAME:-bottlecap-thinkingcap-rtx}")
MTP=$(_runtime_escape "$mtp")
PREFIX_CACHE=$(_runtime_escape "$prefix_cache")
HF_HOME=/hf
HF_HUB_OFFLINE=1
VLLM_ALLOW_LONG_MAX_MODEL_LEN=1
FLASHINFER_CUDA_ARCH_LIST=12.1a
FLASHINFER_DISABLE_VERSION_CHECK=1
TORCH_CUDA_ARCH_LIST=12.1a
EOF

	if [[ -n "${VLLM_API_KEY:-}" ]]; then
		printf 'VLLM_API_KEY=%s\n' "$(_runtime_escape "$VLLM_API_KEY")" >>"$out"
	fi

	echo "resolve: wrote $out (hash=${hash:0:12}… snap=$snap_in served=$served)"
}
